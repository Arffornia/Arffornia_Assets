// Builds the Arffornia design tokens (spec 018) into CSS, JSON and Java, and checks WCAG contrast.
//   node ui/tokens/build.mjs           write ui/tokens/dist/*
//   node ui/tokens/build.mjs --check   fail if dist/ is stale or a contrast pair is below its minimum
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SOURCE = path.join(HERE, 'arffornia.tokens.json');
const DIST = path.join(HERE, 'dist');
const THEMES = ['dark', 'light'];

export function flatten(node, prefix = [], out = {}) {
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    if (value && typeof value === 'object' && '$value' in value) out[[...prefix, key].join('.')] = value.$value;
    else if (value && typeof value === 'object') flatten(value, [...prefix, key], out);
  }
  return out;
}

export function resolve(flat) {
  const seen = new Set();
  const get = (key) => {
    if (!(key in flat)) throw new Error(`unknown token reference {${key}}`);
    if (seen.has(key)) throw new Error(`reference cycle at {${key}}`);
    seen.add(key);
    const value = flat[key];
    const match = typeof value === 'string' && value.match(/^\{(.+)\}$/);
    const result = match ? get(match[1]) : value;
    seen.delete(key);
    return result;
  };
  return Object.fromEntries(Object.keys(flat).map((key) => [key, get(key)]));
}

function luminance(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

export function contrast(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

export function contrastFailures(tokens, pairs) {
  const failures = [];
  for (const theme of THEMES) {
    for (const [fg, bg, min] of pairs) {
      const ratio = contrast(tokens[`theme.${theme}.${fg}`], tokens[`theme.${theme}.${bg}`]);
      if (ratio < min) failures.push(`${theme}: ${fg} on ${bg} is ${ratio.toFixed(2)}, needs ${min}`);
    }
  }
  return failures;
}

const cssName = (key) => `--arf-${key.replace(/\./g, '-')}`;
const cssValue = (value) => (Array.isArray(value) ? value.map((f) => (f.includes(' ') ? `"${f}"` : f)).join(', ') : value);

export function toCss(tokens) {
  const shared = Object.entries(tokens).filter(([k]) => !k.startsWith('theme.') && !k.startsWith('contrast.'));
  const theme = (name) => Object.entries(tokens).filter(([k]) => k.startsWith(`theme.${name}.`))
    .map(([k, v]) => `  --arf-${k.slice(`theme.${name}.`.length)}: ${v};`).join('\n');
  return `/* Generated by ui/tokens/build.mjs from arffornia.tokens.json. Do not edit. */
:root {
${shared.map(([k, v]) => `  ${cssName(k)}: ${cssValue(v)};`).join('\n')}
}

/* Dark is the default (launcher, game). The website opts into light with data-theme="light". */
:root, [data-theme="dark"] {
  color-scheme: dark;
${theme('dark')}
}

[data-theme="light"] {
  color-scheme: light;
${theme('light')}
}
`;
}

export function toJava(tokens) {
  const constName = (key) => key.replace(/^theme\./, '').replace(/[.-]/g, '_').toUpperCase();
  const argb = (hex) => `0xFF${hex.slice(1).toUpperCase()}`;
  const colours = Object.entries(tokens).filter(([k, v]) => typeof v === 'string' && /^#[0-9a-f]{6}$/i.test(v)
    && (k.startsWith('theme.dark.') || k.startsWith('color.tier.') || k.startsWith('color.state.')));
  return `// Generated by Arffornia_Assets ui/tokens/build.mjs from arffornia.tokens.json. Do not edit.
package fr.thegostsniperfr.arffornia.client.ui;

/** Arffornia design tokens (spec 018): ARGB colours of the dark theme, stage accents and states. */
public final class ArfTokens {
    private ArfTokens() {
    }

${colours.map(([k, v]) => `    public static final int ${constName(k)} = ${argb(v)};`).join('\n')}
}
`;
}

export function build() {
  const source = JSON.parse(fs.readFileSync(SOURCE, 'utf8'));
  const tokens = resolve(flatten(source));
  return {
    tokens,
    failures: contrastFailures(tokens, source.contrast.pairs.$value),
    files: {
      'tokens.css': toCss(tokens),
      'tokens.json': `${JSON.stringify(tokens, null, 2)}\n`,
      'ArfTokens.java': toJava(tokens),
    },
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { failures, files } = build();
  const check = process.argv.includes('--check');
  const stale = [];
  if (!check) fs.mkdirSync(DIST, { recursive: true });
  for (const [name, content] of Object.entries(files)) {
    const file = path.join(DIST, name);
    if (check) {
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) stale.push(name);
    } else {
      fs.writeFileSync(file, content);
    }
  }
  for (const failure of failures) console.error(`contrast: ${failure}`);
  for (const name of stale) console.error(`stale: ui/tokens/dist/${name} (run npm run tokens)`);
  if (failures.length || stale.length) process.exit(1);
  console.log(check ? 'tokens: up to date, contrast OK' : `tokens: wrote ${Object.keys(files).join(', ')}`);
}
