#!/usr/bin/env node
// Model lint: physical plausibility, block grid, ports, animation sweeps, mechanics (cantilevers,
// belts, gears, joints), texel density, budget.
//
//   node tools/lint/lint.mjs                 every model in models/ and concepts/
//   node tools/lint/lint.mjs smelter         only the models whose id contains "smelter"
//   node tools/lint/lint.mjs --snap          also render out/lint/<id>.png with the faulty parts in magenta
//   node tools/lint/lint.mjs --strict        legacy mocks gate too (status "mock" is report-only by default)
//
// Writes out/lint/<id>.json, out/lint/<id>.md and out/lint/README.md (the summary).
// Exit code 1 when a gating model has an error: this is the CI gate.
import fs from 'node:fs';
import path from 'node:path';
import { lintModel } from './checks.mjs';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
const OUT = path.join(ROOT, 'out/lint');
const args = process.argv.slice(2);
const flag = (f) => args.includes(f);
const filters = args.filter((a) => !a.startsWith('--'));
const rules = JSON.parse(fs.readFileSync(path.join(ROOT, 'tools/lint/rules.json'), 'utf8'));

export function discover(root = ROOT) {
  const found = [];
  const dir = path.join(root, 'models');
  if (fs.existsSync(dir)) for (const d of fs.readdirSync(dir).sort()) { const f = path.join(dir, d, `${d}.bbmodel`); if (fs.existsSync(f)) found.push({ id: d, file: f }); }
  const cdir = path.join(root, 'concepts');
  if (fs.existsSync(cdir)) for (const dd of fs.readdirSync(cdir).sort()) {
    const sub = path.join(cdir, dd); if (!fs.statSync(sub).isDirectory()) continue;
    for (const m of fs.readdirSync(sub).sort()) { const f = path.join(sub, m, `${m}.bbmodel`); if (fs.existsSync(f)) found.push({ id: `${dd}/${m}`, file: f }); }
  }
  return found;
}

// colour per check in the snapshot: geometry problems only (texel and budget are not about a place)
export const COLOURS = { overlap: '#ff2bd6', sweep: '#e5193b', floating: '#ff8a00', footprint: '#f2c200', ports: '#00a3ff', zfight: '#8a3cff', cantilever: '#00c48c', belt: '#7a5cff', kinematics: '#ff5a1f' };
const highlights = (r) => { const m = {}; for (const f of r.findings) if (f.level === 'error' && COLOURS[f.check]) for (const p of f.parts) m[p] ||= COLOURS[f.check]; return m; };

const ICON = { error: 'ERROR', warn: 'warn', info: 'info' };
function markdown(r) {
  const s = r.stats;
  const lines = [`# ${r.title} (\`${r.id}\`)`, '',
    `**${r.pass ? 'PASS' : 'FAIL'}**: ${r.errors} error(s), ${r.warnings} warning(s). Status \`${r.status}\`${r.gating ? '' : ' (legacy mock: reported, not gating)'}.`, '',
    `| Footprint | Size (blocks) | Elements | Triangles | Animated bones | Texture | Texel median |`, '|---|---|---|---|---|---|---|',
    `| ${r.footprint ? r.footprint.join('×') : 'none'}${r.height ? `×${r.height}` : ''} | ${s.size.join(' × ')} | ${s.elements} | ${s.tris} | ${s.animatedBones} | ${Math.round(s.texturePx / 1024)}k px | ${s.texelMedian} px/block |`, ''];
  if (fs.existsSync(path.join(OUT, `${r.id}.png`))) lines.push(`![parts flagged by the lint](./${path.basename(r.id)}.png)`, '', `Colours: ${Object.entries(COLOURS).map(([k, c]) => `${k} \`${c}\``).join(', ')}. Blue wire: the claimed block grid. Rest pose.`, '');
  const by = new Map(); for (const f of r.findings) by.set(f.check, [...(by.get(f.check) || []), f]);
  for (const [check, fs_] of by) { lines.push(`## ${check}`, ''); for (const f of fs_) lines.push(`- **${ICON[f.level]}** ${f.msg}`); lines.push(''); }
  if (!r.findings.length) lines.push('No findings.', '');
  return lines.join('\n');
}

export function summary(results) {
  const rows = results.map((r) => `| [${r.id}](./${r.id}.md) | ${r.status} | ${r.pass ? 'pass' : '**fail**'}${r.gating ? '' : ' (not gating)'} | ${r.errors} | ${r.warnings} | ${[...new Set(r.findings.filter((f) => f.level === 'error').map((f) => f.check))].join(', ') || ''} | ${r.stats.tris} |`);
  return ['# Model lint report', '', 'Generated by `npm run lint`. Rules: [docs/MODEL-RULES.md](../../docs/MODEL-RULES.md).', '',
    '| Model | Status | Result | Errors | Warnings | Failing checks | Triangles |', '|---|---|---|---|---|---|---|', ...rows, ''].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  const list = discover().filter((m) => !filters.length || filters.some((f) => m.id.includes(f)));
  fs.mkdirSync(OUT, { recursive: true });
  const results = [];
  for (const m of list) {
    const json = JSON.parse(fs.readFileSync(m.file, 'utf8'));
    const r = lintModel(json, rules, { id: m.id });
    if (flag('--strict')) r.gating = true;
    results.push(r);
    fs.mkdirSync(path.dirname(path.join(OUT, m.id)), { recursive: true });
    fs.writeFileSync(path.join(OUT, `${m.id}.json`), JSON.stringify(r, null, 1) + '\n');
    console.log(`${r.pass ? 'pass' : 'FAIL'} ${m.id.padEnd(34)} ${String(r.errors).padStart(3)} errors ${String(r.warnings).padStart(3)} warnings${r.gating ? '' : '  (mock, not gating)'}`);
    for (const f of r.findings.filter((x) => x.level === 'error').slice(0, flag('--verbose') ? 1e9 : 4)) console.log(`     ${f.check.padEnd(10)} ${f.msg}`);
  }
  if (flag('--snap')) {
    const { snapshots } = await import('./snapshot.mjs');
    await snapshots(results.map((r) => ({ id: r.id, file: list.find((m) => m.id === r.id).file, parts: highlights(r) })), OUT);
  }
  for (const r of results) fs.writeFileSync(path.join(OUT, `${r.id}.md`), markdown(r));
  if (!filters.length) fs.writeFileSync(path.join(OUT, 'README.md'), summary(results));
  const failed = results.filter((r) => r.gating && !r.pass);
  if (failed.length) { console.error(`\n${failed.length} gating model(s) fail the lint: ${failed.map((r) => r.id).join(', ')}`); process.exit(1); }
}
